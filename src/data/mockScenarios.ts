// Helper to generate realistic continuous single-pass telemetry
function generateTelemetry(
  count: number,
  startLat: number,
  startLon: number,
  baseAlt: number,
  speedMps: number,
  headingDeg: number,
  gimbalPitch: number
) {
  const frames = [];
  const dt = 0.5; // half second intervals
  const latStep = (speedMps * dt * Math.cos((headingDeg * Math.PI) / 180)) / 111139;
  const lonStep = (speedMps * dt * Math.sin((headingDeg * Math.PI) / 180)) / (111139 * Math.cos((startLat * Math.PI) / 180));

  for (let i = 0; i < count; i++) {
    const t = i * dt;
    // Gentle drone turbulence & IMU micro-oscillations
    const imuRoll = Math.sin(t * 1.5) * 1.2 + (Math.random() - 0.5) * 0.4;
    const imuPitch = Math.cos(t * 1.1) * 0.9 + (Math.random() - 0.5) * 0.3;
    const imuYaw = headingDeg + Math.sin(t * 0.6) * 1.5;
    const altDrift = Math.sin(t * 0.3) * 1.2;

    frames.push({
      frameIndex: i * 15,
      timeSec: parseFloat(t.toFixed(1)),
      latitude: startLat + latStep * i,
      longitude: startLon + lonStep * i,
      altitudeMeters: parseFloat((baseAlt + altDrift).toFixed(2)),
      relativeAltMeters: parseFloat((baseAlt + altDrift - 24.5).toFixed(2)),
      speedMps: parseFloat((speedMps + Math.sin(t * 0.8) * 0.3).toFixed(1)),
      headingDeg: parseFloat(imuYaw.toFixed(1)),
      gimbalPitchDeg: parseFloat((gimbalPitch + Math.sin(t * 2) * 0.4).toFixed(1)),
      gimbalRollDeg: parseFloat((-imuRoll * 0.85).toFixed(2)),
      gimbalYawDeg: parseFloat(headingDeg.toFixed(1)),
      imuRoll: parseFloat(imuRoll.toFixed(2)),
      imuPitch: parseFloat(imuPitch.toFixed(2)),
      imuYaw: parseFloat(imuYaw.toFixed(2)),
      rtkStatus: 'RTK_FIXED' as const,
      satellites: 26 + (i % 4),
      hdop: 0.65 + (i % 3) * 0.05,
      vdop: 0.85 + (i % 3) * 0.06,
      detectedFeatures: 1420 + Math.floor(Math.sin(t) * 180 + Math.random() * 80),
      blurIndex: parseFloat((0.08 + Math.abs(imuRoll) * 0.03 + Math.random() * 0.04).toFixed(3)),
      dynamicObjectsMasked: (i % 5 === 0) ? Math.floor(Math.random() * 4) + 1 : 0,
    });
  }
  return frames;
}

